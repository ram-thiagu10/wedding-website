  function makeParticle(spawnAtTop){
    const size = Math.random() * 2.6 + 1;
    return {
      x: Math.random() * w,
      y: spawnAtTop ? -10 - Math.random() * h : Math.random() * h,
      size: size,
      baseSize: size,
      speedY: Math.random() * 0.5 + 0.25,
      drift: (Math.random() - 0.5) * 0.4,
      color: colors[Math.floor(Math.random() * colors.length)],
      twinkleSpeed: Math.random() * 0.03 + 0.015,
      twinklePhase: Math.random() * Math.PI * 2,
      opacity: Math.random() * 0.5 + 0.4
    };
  }

  // Density scales gently with screen size, capped for performance
  function targetCount(){
    return Math.min(70, Math.floor((w * h) / 18000));
  }

  function initParticles(){
    particles = [];
    const count = targetCount();
    for (let i = 0; i < count; i++){
      particles.push(makeParticle(false));
    }
  }

  function drawStar(p, twinkle){
    ctx.save();
    ctx.globalAlpha = p.opacity * twinkle;
    ctx.translate(p.x, p.y);
    ctx.fillStyle = p.color;
    ctx.shadowColor = p.color;
    ctx.shadowBlur = p.size * 2.5;
    const r = p.size;
    ctx.beginPath();
    for (let i = 0; i < 4; i++){
      ctx.rotate(Math.PI / 2);
      ctx.moveTo(0, 0);
      ctx.lineTo(0, r);
    }
    ctx.lineWidth = r * 0.5;
    ctx.strokeStyle = p.color;
    ctx.stroke();
    ctx.beginPath();
    ctx.arc(0, 0, r * 0.35, 0, Math.PI * 2);
    ctx.fill();
    ctx.restore();
  }

  function animate(){
    if (!running) return;
    ctx.clearRect(0, 0, w, h);

    for (let p of particles){
      p.y += p.speedY;
      p.x += p.drift;
      p.twinklePhase += p.twinkleSpeed;

      if (p.y > h + 10){
        Object.assign(p, makeParticle(true), { y: -10 });
      }
      if (p.x < -10) p.x = w + 10;
      if (p.x > w + 10) p.x = -10;

      const twinkle = 0.5 + 0.5 * Math.sin(p.twinklePhase);
      drawStar(p, twinkle);
    }

    rafId = requestAnimationFrame(animate);
  }

  function startSparkles(){
    if (running) return;
    running = true;
    initParticles();
    animate();
  }

  function stopSparkles(){
    running = false;
    if (rafId) cancelAnimationFrame(rafId);
    ctx.clearRect(0, 0, w, h);
  }

  // Respect users who prefer reduced motion
